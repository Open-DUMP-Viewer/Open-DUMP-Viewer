#ifndef ODV_TZDATA_H
#define ODV_TZDATA_H

#include <stdint.h>

/* rule_from value meaning "the POSIX rule applies at every instant" */
#define ODV_TZ_NO_LIMIT  INT64_MIN

/* One date of a POSIX TZ rule ("Mm.w.d/time", "Jn/time" or "n/time") */
typedef struct {
    char     kind;       /* 'M', 'J' or 'N' */
    uint8_t  month;      /* M: 1-12 */
    uint8_t  week;       /* M: 1-5 (5 = last) */
    uint8_t  wday;       /* M: 0 = Sunday */
    int16_t  yday;       /* J: 1-365 (Feb 29 never counted), N: 0-365 */
    int32_t  secs;       /* local time of day of the change; may be < 0 or >= 86400 */
} ODV_TZ_RULEDATE;

/* POSIX TZ rule from the TZif footer (used after a zone's explicit transitions) */
typedef struct {
    int32_t  std_off;    /* UTC offset of standard time, seconds east of UTC */
    int32_t  dst_off;    /* UTC offset of daylight time (== std_off without DST) */
    uint8_t  has_dst;
    ODV_TZ_RULEDATE start;  /* change to daylight time (in local standard time) */
    ODV_TZ_RULEDATE end;    /* change back (in local daylight time) */
} ODV_TZ_RULE;

/* Transition gaps are stored in units of this many seconds (odv_tz_trans_d16);
   ODV_TZ_DELTA_LONG means "the next odv_tz_trans_long entry, in seconds". */
#define ODV_TZ_DELTA_UNIT  1800
#define ODV_TZ_DELTA_LONG  0xFFFF

/* One zone: explicit transitions before rule_from, the POSIX rule from then on */
typedef struct {
    int64_t  first;        /* UTC seconds of the first stored transition */
    int64_t  rule_from;    /* the rule applies at and after this instant */
    uint16_t trans_start;  /* first index into odv_tz_trans_d16 / odv_tz_trans_off */
    uint16_t trans_count;
    uint16_t long_start;   /* first index into odv_tz_trans_long */
    uint16_t rule;         /* index into odv_tz_rules */
    int32_t  init_off;     /* UTC offset (seconds) before the first transition (LMT) */
} ODV_TZ_ZONE;

/* Oracle region id -> name / zone */
typedef struct {
    uint16_t id;           /* Oracle region id (13 bits) */
    uint16_t name;         /* byte offset of the NUL-terminated name in odv_tz_names */
    uint16_t zone;         /* index into odv_tz_zones */
} ODV_TZ_REGION;

extern const char          odv_tzdata_version[];
extern const int32_t       odv_tz_offsets[];
extern const ODV_TZ_RULE   odv_tz_rules[];
extern const uint16_t      odv_tz_trans_d16[];
extern const uint32_t      odv_tz_trans_long[];
extern const uint8_t       odv_tz_trans_off[];
extern const ODV_TZ_ZONE   odv_tz_zones[];
extern const char          odv_tz_names[];
extern const ODV_TZ_REGION odv_tz_regions[];
extern const int           odv_tz_region_count;

#endif /* ODV_TZDATA_H */
