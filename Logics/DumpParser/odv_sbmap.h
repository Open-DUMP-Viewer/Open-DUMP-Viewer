/*****************************************************************************
    Open DUMP Viewer for Oracle database

    odv_sbmap.h
    Layout of the generated single-byte character set tables (odv_sbmap.c).

    odv_sbmap.c is generated by tools/sbmap/gen_sbmap.py from Oracle's own
    conversions (UTL_RAW.CONVERT to / from AL32UTF8 for every byte of every
    character set whose maximum character size is 1; identical on 11.2 / 21c
    / 23.26 for the character sets each of them has).  Only odv_sb.c reads
    these tables.

    Copyright (C) 2026 YANAI Taketo
 *****************************************************************************/

#ifndef ODV_SBMAP_H
#define ODV_SBMAP_H

#include <stddef.h>
#include <stdint.h>

/* A character that several bytes decode to, and the byte Oracle converts it
   back to. */
typedef struct {
    uint16_t ucs;
    uint8_t  byte;
} ODV_SBMAP_REV;

typedef struct {
    uint16_t             id;        /* NLS_CHARSET_ID */
    const char          *name;      /* Oracle character set name */
    const uint16_t      *lo;        /* Unicode of bytes 00-7F; NULL = the same as US-ASCII */
    const uint16_t      *hi;        /* Unicode of bytes 80-FF */
    const ODV_SBMAP_REV *rev;       /* characters with more than one byte (may be NULL) */
    int                  rev_count;
    uint8_t              repl;      /* Oracle's replacement for a character the set lacks */
} ODV_SBMAP_CHARSET;

extern const ODV_SBMAP_CHARSET odv_sbmap_charsets[];   /* sorted by id */
extern const int odv_sbmap_charset_count;

#endif /* ODV_SBMAP_H */
